def test_csv_building_source_null_literal_parsed_as_nan(tmp_path):
    """Regression guard: a Postgres/pgAdmin CSV export's literal "NULL"
    text must not survive as the string "NULL" -- it has to become real
    NaN, or downstream float()/int() conversions elsewhere in the
    pipeline would break on it. This was a real quirk of the original
    city2tabula export (see module docstring); the current bundled
    dataset no longer exercises it (its own construction_year is fully
    populated from real BAG data), so this test now builds a tiny
    synthetic fixture directly -- decoupled from whatever the bundled
    data happens to contain, and still a real guard on the
    ``na_values=["NULL"]`` behavior itself."""
    (tmp_path / "lod2_building_feature.csv").write_text(
        "building_feature_id,tabula_variant_code_id,construction_year\n"
        "1,10,1990\n"
        "2,NULL,NULL\n",
        encoding="utf-8",
    )
    (tmp_path / "lod2_child_feature_surface.csv").write_text(
        "id,building_feature_id,surface_feature_id,objectclass_id,classname,surface_area\n"
        "a,1,1,710,GroundSurface,50.0\n",
        encoding="utf-8",
    )
    (tmp_path / "tabula.csv").write_text("id,Code_Country\n10,NL\n", encoding="utf-8")

    source = CsvBuildingSource(tmp_path)
    assert source.buildings["construction_year"].isna().any()
    non_na = source.buildings["construction_year"].dropna()
    assert not (non_na.astype(str) == "NULL").any()
    # tabula_variant_code_id=NULL must become real <NA>, not the string "NULL"
    assert source.buildings["tabula_variant_code_id"].isna().any()


