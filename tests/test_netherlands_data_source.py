# ── clean CityJSON regeneration: verification guards (2026-08-16) ────────
#
# The original city2tabula CSV export carried two independent,
# compounding duplicate-geometry bugs (see .claude/residential/
# resolved.md's "Netherlands (Loenen) building data" entry: an exact-
# duplicate-row layer, fixed first in CsvBuildingSource; and a second
# "near-identical batch" layer found while cross-checking that fix
# against real CityJSON ground truth, never safely fixable from the
# export alone). Both are now moot: the dataset was regenerated from
# scratch, directly from CityJSON, via
# buem.buildings.datasources.cityjson_extractor -- see its own docstring
# for the full methodology (party-wall geometric coincidence detection,
# storeys estimation, etc.). CsvBuildingSource's dedup/aggregate-recompute
# logic (added for the city2tabula export) still runs over this data too,
# but is now a no-op by construction -- there is nothing left to dedupe.
# These tests confirm exactly that, plus the regenerated numbers for one
# building independently ground-truthed against CityJSON during the same
# investigation.


@requires_nl_data
def test_csv_building_source_no_exact_duplicates_dataset_wide():
    """No (building_feature_id, surface_feature_id, classname, surface_area,
    tilt, azimuth, height, is_valid, is_planar) combination should appear
    more than once anywhere in the loaded surfaces table -- true by
    construction for the CityJSON-derived data (one row per real face,
    no fragmentation/duplication step exists), unlike the old city2tabula
    export."""
    source = CsvBuildingSource(NL_DATA_DIR)
    key_cols = [c for c in source.surfaces.columns if c not in ("id", "child_row_id")]
    assert not source.surfaces.duplicated(subset=key_cols).any()


@requires_nl_data
def test_csv_building_source_matches_cityjson_ground_truth_for_known_building():
    """The known building (see _KNOWN_BAG_PAND_ID) reproduces exactly the
    numbers independently computed straight from CityJSON during the
    2026-08-16 investigation: 4 walls/80.48 m2, 1 roof/39.84 m2, 1
    floor/39.43 m2, built 1907, single storey."""
    source = CsvBuildingSource(NL_DATA_DIR)
    match = source.buildings[source.buildings["bag_pand_id"] == _KNOWN_BAG_PAND_ID]
    assert len(match) == 1
    brow = match.iloc[0]
    bid = int(brow["building_feature_id"])
    surfaces = source.get_surfaces_for_building(bid)

    by_class = surfaces["classname"].value_counts().to_dict()
    assert by_class == {"WallSurface": 4, "RoofSurface": 1, "GroundSurface": 1}

    assert brow["area_total_wall"] == pytest.approx(80.48443, abs=1e-3)
    assert brow["area_total_roof"] == pytest.approx(39.83981, abs=1e-3)
    assert brow["area_total_floor"] == pytest.approx(39.43053, abs=1e-3)
    assert int(brow["number_of_storeys"]) == 1
    assert int(brow["construction_year"]) == 1907
    # geometry-derived aggregates must match a fresh sum over the surfaces
    # themselves too (CsvBuildingSource's recompute step, now a no-op here)
    wall_area = surfaces.loc[surfaces["classname"] == "WallSurface", "surface_area"].sum()
    assert brow["area_total_wall"] == pytest.approx(wall_area)
