"""
Tests for ``CsvBuildingSource`` and ``geometry_utils`` (WKB point decoding
+ RD-New -> WGS84 reprojection), built for the real Netherlands/Loenen
data under ``src/buem/data/buildings/netherlands/Loenen/``.

**Data provenance changed 2026-08-16**: this data was originally a
city2tabula-derived CSV export, which turned out to carry two independent,
compounding duplicate-geometry bugs (see ``.claude/residential/
resolved.md``'s "Netherlands (Loenen) building data" entry for the full
story). It has since been **replaced entirely** with a clean, single-pass
extraction straight from the real CityJSON (3D BAG) source
(``buem.buildings.datasources.cityjson_extractor`` -- see that module's
own docstring for the extraction/party-wall/storeys methodology). The old
city2tabula CSVs are kept for reference under
``src/buem/data/buildings/netherlands/Loenen/_city2tabula_backup/`` but are no
longer read by anything. Building IDs are a fresh sequential scheme
(``cityjson_extractor`` assigns them in sorted-BAG-pand-id order) --
**not** the old city2tabula ``building_feature_id`` values referenced in
earlier commits/docs (e.g. "building 37206" no longer exists; the same
physical building is now identified by its stable ``bag_pand_id``, looked
up below rather than hardcoded).

**TABULA archetype matching landed 2026-08-17**
(``buem.buildings.datasources.nl_archetype_mapper`` -- see its module
docstring for the full methodology: real construction year/geometry-
derived building type, a real energy label as an override where present,
matched against the real bundled Dutch TABULA sheet). Almost every
building now has a real ``tabula_variant_code_id`` -- the ~4/3,105
flagged non-residential (greenhouse/warehouse/glasshouse) are the
deliberate exception. ``LOD2Mapper.map_building()`` succeeds end-to-end
for the vast majority of buildings in this dataset as of that date.

Gated the same way ``test_live_synthesis.py`` gates on the bundled
German workbook: these files are real data, not fixtures generated by
this repo, and may not be present in every environment (fresh checkout,
CI). Skip cleanly rather than fail when absent.
"""
from __future__ import annotations

