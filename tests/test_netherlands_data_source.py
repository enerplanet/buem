# ── geometry_utils: pure decoding, no I/O ────────────────────────────────


def test_wkb_point_to_lat_lon_known_coordinate():
    """A real hex WKB point from the original city2tabula Loenen export,
    hand-verified against its expected RD-New raw coordinates
    (197639.15, 461826.02) before this module existed. Pure decode test --
    independent of which building dataset is currently loaded."""
    hex_wkb = "010100002040710000DE22EC3639200841F10E781208301C41"
    lat, lon = wkb_point_to_lat_lon(hex_wkb)
    # Loenen, Gelderland, NL -- roughly 52.14N, 6.01E
    assert 52.0 < lat < 52.3
    assert 5.9 < lon < 6.1


def test_wkb_point_to_lat_lon_rejects_non_point():
    # A MultiPolygon Z EWKB header (type 6, with SRID+Z flags) -- not a
    # POINT, must raise rather than silently misinterpret the bytes.
    fake_multipolygon_header = "01060000A040710000" + "00" * 8
    with pytest.raises(ValueError, match="expected a POINT"):
        wkb_point_to_lat_lon(fake_multipolygon_header)


def test_building_lat_lon_returns_none_for_missing_geometry():
    import pandas as pd

    row = pd.Series({"building_centroid_geom": None})
    assert building_lat_lon(row) is None

    row_nan = pd.Series({"building_centroid_geom": float("nan")})
    assert building_lat_lon(row_nan) is None


def test_building_lat_lon_returns_none_and_warns_on_malformed_geometry(caplog):
    import pandas as pd

    row = pd.Series({"building_centroid_geom": "not-valid-hex"})
    with caplog.at_level("WARNING"):
        result = building_lat_lon(row)
    assert result is None


def test_region_center_lat_lon_averages_only_decodable_rows():
    """A row without geometry must be skipped, not counted as (0, 0) --
    which would drag the region's shared weather fetch into the Atlantic."""
    import pandas as pd

    from buem.buildings.mapping.geometry_utils import region_center_lat_lon

    hex_wkb = "010100002040710000DE22EC3639200841F10E781208301C41"
    expected_lat, expected_lon = wkb_point_to_lat_lon(hex_wkb)
    df = pd.DataFrame({"building_centroid_geom": [hex_wkb, None, hex_wkb]})

    lat, lon = region_center_lat_lon(df)

    assert lat == pytest.approx(expected_lat)
    assert lon == pytest.approx(expected_lon)


def test_region_center_lat_lon_raises_when_no_geometry_at_all():
    """Falling back to a module-default location here would simulate a
    region against another country's climate."""
    import pandas as pd

    from buem.buildings.mapping.geometry_utils import region_center_lat_lon

    with pytest.raises(ValueError, match="no building.*real geometry|No building"):
        region_center_lat_lon(pd.DataFrame({"building_centroid_geom": [None, None]}))


